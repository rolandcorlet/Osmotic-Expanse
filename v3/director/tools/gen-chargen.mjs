// Lifts the Players Assistant's proven character maths (ATLAS data + OSMOTIC model + the blank sheet)
// out of chargen/osmotic-generator.html, unchanged, into an ES module. Run: node tools/gen-chargen.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const src = readFileSync(new URL('../../../chargen/osmotic-generator.html', import.meta.url), 'utf8');
const block = (start) => {
  const i = src.indexOf(start); if (i < 0) throw new Error(`missing ${start}`);
  const j = src.indexOf('\n};', i); return src.slice(i, j + 3);
};
// Plain-words book text for the builder's cards (portraits are saved as files, not inlined here).
const oxI = src.indexOf('var OXX = '), oxJ = src.indexOf('\n', oxI);
const OXX = JSON.parse(src.slice(oxI + 10, oxJ).trim().replace(/;$/, ''));
for (const v of Object.values(OXX.lin || {})) delete v.portrait;
const blankI = src.indexOf('function blank()'), blankJ = src.indexOf('\n}', blankI);
const out = `// GENERATED by tools/gen-chargen.mjs from chargen/osmotic-generator.html. Do not edit by hand.
/* eslint-disable */
${block('var ATLAS = ')}
${block('var OSMOTIC = ')}
${src.slice(blankI, blankJ + 2)}
const INFO = ${JSON.stringify(OXX)};
export { ATLAS, OSMOTIC, blank, INFO };
`;
writeFileSync(new URL('../data/chargen/model.generated.js', import.meta.url), out);
console.log('model.generated.js', out.length, 'chars');
