// Reads the original Director's Codex and writes every numbered section as lines of the book's own text,
// so the v3 edition carries every table and number exactly as printed.
//   node tools/gen-codex.mjs   ->  data/kit/codex.generated.js
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(new URL('../../../The Osmotic Expanse - DIRECTOR\'S CODEX.md', import.meta.url), 'utf8').replace(/\r/g, '');
const lines = src.split('\n');
const clean = (t) => String(t || '').replace(/\*\*/g, '').replace(/(^|[^*\w])\*([^*\n]+)\*/g, '$1$2').replace(/`/g, '').replace(/\s+/g, ' ').trim();

const chapters = {};
const sections = [];
let cur = null;
let tableHead = null;
let inCode = false;
for (let i = 0; i < lines.length; i++) {
  const l = lines[i];
  const ch = l.match(/^# (\d+) · (.+)$/);
  if (ch) { chapters[ch[1]] = clean(ch[2]); cur = ch[1] === '12' || ch[1] === '13' || true ? { chapter: ch[1], sec: ch[1], title: clean(ch[2]), lines: [], chapterHead: true } : null; sections.push(cur); tableHead = null; continue; }
  const sc = l.match(/^## (\d+)\.(\d+) (.+)$/);
  if (sc) { cur = { chapter: sc[1], sec: `${sc[1]}.${sc[2]}`, title: clean(sc[3]), lines: [] }; sections.push(cur); tableHead = null; continue; }
  if (!cur || /^# |^---$/.test(l)) continue;
  if (/^```/.test(l)) { inCode = !inCode; continue; }
  if (!l.trim()) { tableHead = null; continue; }
  if (inCode) { cur.lines.push(l.trim()); continue; }
  if (l.startsWith('|')) {
    const cells = l.split('|').slice(1, -1).map((c) => clean(c));
    if (cells.every((c) => /^:?-+:?$/.test(c) || c === '')) continue;
    if (!tableHead) { tableHead = cells; cur.lines.push(`(${cells.join(' | ')})`); continue; }
    cur.lines.push(`${cells[0]}: ${cells.slice(1).filter(Boolean).join(' · ')}`);
    continue;
  }
  if (/^### /.test(l)) { cur.lines.push(`${clean(l.replace(/^###\s*/, ''))}`); continue; }
  const t = clean(l.replace(/^\s*[*-]\s+/, '').replace(/^>\s*/, ''));
  if (t) cur.lines.push(t);
}
const out = sections.filter((s) => s.lines.length).map((s) => ({ id: s.chapterHead ? `codex-${s.chapter}` : `codex-${s.sec.replace('.', '-')}`, sec: s.sec, chapter: s.chapter, chapterName: chapters[s.chapter], title: s.title, lines: s.lines }));
writeFileSync(new URL('../data/kit/codex.generated.js', import.meta.url), `// GENERATED by tools/gen-codex.mjs from "The Osmotic Expanse - DIRECTOR'S CODEX.md". Do not edit by hand:
// change the book, then run the generator. These are the book's own words, tables and numbers.
export const CODEX_CHAPTERS = ${JSON.stringify(chapters, null, 1)};
export const CODEX_SECTIONS = ${JSON.stringify(out, null, 1)};
`);
console.log(`${out.length} sections, ${out.reduce((n, s) => n + s.lines.length, 0)} lines`);
console.log(out.map((s) => `${s.sec}(${s.lines.length})`).join(' '));
